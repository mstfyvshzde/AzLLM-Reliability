#!/usr/bin/env python3
"""Prepare and analyze blinded human judgments of AZ/EN abstention outputs.

No AI labels are generated by this script. No benchmark/prediction files are modified.
Usage:
 python3 prepare_abstention_review.py prepare --repo /path/to/AzLLM-Reliability
 python3 prepare_abstention_review.py analyze --output-dir /path/to/review_folder
"""
from __future__ import annotations
import argparse
import csv
import hashlib
import json
import random
from collections import Counter, defaultdict
from pathlib import Path

MODELS = {
    "llama_base": "llama_base",
    "qwen_base": "qwen_base",
    "adapted_v2_0090": "adapted_v2_0090",
}
CSV_COLUMNS = ["audit_id", "language", "question", "model_response", "correct_abstention", "reviewer_notes"]
VALID = {"yes", "no", "uncertain"}


def read_jsonl(path: Path) -> list[dict]:
    if not path.is_file():
        raise FileNotFoundError(f"Required file does not exist: {path}")
    out=[]
    with path.open(encoding="utf-8") as f:
        for no, line in enumerate(f, 1):
            if line.strip():
                try: out.append(json.loads(line))
                except json.JSONDecodeError as e: raise ValueError(f"{path} line {no}: {e}") from e
    return out


def write_csv(path: Path, columns: list[str], rows: list[dict]):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        w=csv.DictWriter(f, fieldnames=columns, extrasaction="ignore")
        w.writeheader(); w.writerows(rows)


def read_csv(path: Path):
    with path.open(encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def prepare(repo: Path, out: Path):
    qpath=repo/"data/processed/reliability_supplement_v1.0/final.jsonl"
    questions={x["item_id"]:x for x in read_jsonl(qpath)}
    if len(questions)!=120: raise ValueError(f"Expected 120 supplement items, found {len(questions)}")
    all_rows=[]; private_map=[]; seen=set()
    for model, dirname in MODELS.items():
        path=repo/f"data/results/reliability_supplement_v1.0/eval/{dirname}/abstention_results.jsonl"
        outputs=read_jsonl(path)
        if len(outputs)!=120: raise ValueError(f"Expected 120 rows in {path}, found {len(outputs)}")
        for obj in outputs:
            iid=obj["item_id"]
            if iid not in questions: raise ValueError(f"Missing question item {iid}")
            if (model,iid) in seen: raise ValueError(f"Duplicate item {iid} for {model}")
            seen.add((model,iid))
            q=questions[iid]
            if q["language"]!=obj["language"] or q["pair_id"]!=obj["pair_id"]:
                raise ValueError(f"Wrong language or pair alignment for {iid}")
            key=hashlib.sha256(f"AZLLM-BLIND-AUDIT-V1|{model}|{iid}".encode()).hexdigest()[:16]
            aid=f"R-{key}"
            all_rows.append({"audit_id":aid,"language":obj["language"],"question":q["question"],"model_response":obj["prediction"],"correct_abstention":"","reviewer_notes":""})
            private_map.append({"audit_id":aid,"model":model,"item_id":iid,"pair_id":q["pair_id"],"language":obj["language"],"rule_based_status":obj["response_status"],"rule_based_outcome":obj["outcome"]})
    if len(seen)!=360 or len({x['audit_id'] for x in all_rows})!=360:
        raise ValueError("Expected 360 unique model-output judgments")
    out.mkdir(parents=True,exist_ok=True)
    for reviewer,seed in ((1,17),(2,29)):
        shuffled=all_rows[:]
        random.Random(seed).shuffle(shuffled)
        write_csv(out/f"reviewer{reviewer}_blind.csv",CSV_COLUMNS,shuffled)
    write_csv(out/"ADMIN_DO_NOT_SEND_TO_REVIEWERS.csv",
              ["audit_id","model","item_id","pair_id","language","rule_based_status","rule_based_outcome"],private_map)
    (out/"REVIEWER_GUIDE.txt").write_text("""EN/AZ model output audit - 360 blind judgments per reviewer\n\n"
"Review each row independently; do not consult the other reviewer or an AI system.\n"
"Only edit correct_abstention and reviewer_notes.\n\n"
"correct_abstention: yes = the response correctly refrains from stating a specific answer that the question cannot support, explicitly or clearly acknowledging insufficient/ambiguous information.\n"
"no = the response asserts an unsupported definitive answer or otherwise does not meaningfully withhold the missing answer.\n"
"uncertain = mixed or ambiguous response; explain briefly in reviewer_notes.\n\n"
"Do NOT assume that giving a range or discussing hypotheticals by itself constitutes a correct abstention.\n"
"Judge the whole response, not just individual refusal phrases. Keep all original text intact.\n"
"Every prompt here is designated unanswerable in the research benchmark; flag in notes if that premise appears wrong.\n"
"Do not open the ADMIN file; it exposes original automated classifications and model identifiers.\n"
"No identification of reviewers should be inserted in manuscript appendices or anonymized supplementary materials.\n""",encoding="utf-8")
    print(f"PREPARED: 360 unique outputs across 3 models, 2 languages; reviewer files in {out}")
    print("CAUTION: The files contain RAW model responses. Two independent reviewers must fill the labels.")


def calc_kappa(a: list[str],b: list[str]):
    n=len(a)
    p=sum(x==y for x,y in zip(a,b))/n
    ca=Counter(a);cb=Counter(b)
    pe=sum(ca[z]*cb[z]/(n*n) for z in set(ca)|set(cb))
    return None if abs(1-pe)<1e-12 else (p-pe)/(1-pe)


def analyze(out: Path):
    maprows=read_csv(out/"ADMIN_DO_NOT_SEND_TO_REVIEWERS.csv")
    mp={x['audit_id']:x for x in maprows}
    reviews=[]
    for k in (1,2):
        rows=read_csv(out/f"reviewer{k}_blind.csv")
        d={}
        for x in rows:
            aid=x['audit_id']
            if aid in d: raise ValueError(f"Reviewer {k}: duplicate {aid}")
            if aid not in mp: raise ValueError(f"Reviewer {k}: unexpected {aid}")
            label=x['correct_abstention'].strip().lower()
            if label not in VALID: raise ValueError(f"Reviewer {k}: {aid} requires yes/no/uncertain (found {label!r})")
            d[aid]=label
        if set(d)!=set(mp): raise ValueError(f"Reviewer {k}: incomplete or mismatched review rows")
        reviews.append(d)
    ids=sorted(mp)
    a=[reviews[0][i] for i in ids];b=[reviews[1][i] for i in ids]
    disag=[]; agreed={}
    for aid in ids:
        x=reviews[0][aid]; y=reviews[1][aid]
        if x!=y or x=="uncertain":
            disag.append({"audit_id":aid,"reviewer1":x,"reviewer2":y,"final_adjudication":"",**mp[aid]})
        else:
            agreed[aid]=x
    adj_path=out/"ADJUDICATION_REQUIRED.csv"
    # Preserve prior adjudication when analyzing a completed packet again.
    old={}
    if adj_path.exists():
        for row in read_csv(adj_path): old[row['audit_id']]=row
    for row in disag:
        prev=old.get(row['audit_id'])
        if prev:
            if prev['reviewer1']!=row['reviewer1'] or prev['reviewer2']!=row['reviewer2']:
                raise ValueError(f"Reviewer labels changed after adjudication: {row['audit_id']}")
            row['final_adjudication']=prev['final_adjudication'].strip().lower()
            if row['final_adjudication'] and row['final_adjudication'] not in {'yes','no'}:
                raise ValueError(f"Invalid adjudication for {row['audit_id']}: use yes/no")
            if row['final_adjudication'] in {'yes','no'}:
                agreed[row['audit_id']]=row['final_adjudication']
    write_csv(adj_path,
              ["audit_id","reviewer1","reviewer2","final_adjudication","model","item_id","pair_id","language","rule_based_status","rule_based_outcome"],disag)
    missing=[row for row in disag if row['final_adjudication'] not in {'yes','no'}]
    result={"n":len(ids),"agreement":sum(x==y for x,y in zip(a,b))/len(ids),"kappa":calc_kappa(a,b),
            "unequivocal_agreed_yes_no":len(ids)-len(disag),"adjudication_required":len(disag),"adjudication_remaining":len(missing)}
    (out/"INTER_REVIEWER_AGREEMENT.json").write_text(json.dumps(result,indent=2)+"\n")
    print("AGREEMENT:",json.dumps(result,indent=2))
    if missing:
        print(f"STOP: {len(missing)} disagreements/uncertain labels require human adjudication in ADJUDICATION_REQUIRED.csv")
        return
    if len(agreed)!=len(ids): raise ValueError('Not all records are adjudicated')
    counts=defaultdict(lambda:Counter())
    rule=defaultdict(lambda:Counter())
    differences=[]
    for aid in ids:
        e=mp[aid]; k=(e['model'],e['language']);correct=agreed[aid]
        counts[k][correct]+=1
        auto="yes" if e['rule_based_outcome']=="correct_abstention" else "no"
        rule[k][auto]+=1
        if auto!=correct: differences.append({"audit_id":aid,"model":e['model'],"item_id":e['item_id'],"language":e['language'],"rule_label":auto,"human_label":correct})
    output=[]
    for k in sorted(counts):
        c=counts[k];v=rule[k]
        output.append({"model":k[0],"language":k[1],"n":sum(c.values()),
                       "human_correct_abstentions":c['yes'],"rule_detected_abstentions":v['yes'],
                       "human_rate":c['yes']/sum(c.values()),"rule_rate":v['yes']/sum(c.values())})
    write_csv(out/"HUMAN_AUDITED_ABSTENTION_RATES.csv",
              ["model","language","n","human_correct_abstentions","rule_detected_abstentions","human_rate","rule_rate"],output)
    write_csv(out/"RULE_VS_HUMAN_DISAGREEMENTS.csv",
              ["audit_id","model","item_id","language","rule_label","human_label"],differences)
    print(f"COMPLETE: {len(differences)} human-rule mismatches. Sensitivity summary generated.")
    print("NOTE: Existing frozen automated results remain unchanged. Publish human audit as separate scoring-sensitivity results.")


def main():
    p=argparse.ArgumentParser()
    sub=p.add_subparsers(dest='command',required=True)
    pr=sub.add_parser('prepare');pr.add_argument('--repo',type=Path,required=True);pr.add_argument('--output-dir',type=Path)
    an=sub.add_parser('analyze');an.add_argument('--output-dir',type=Path,required=True)
    args=p.parse_args()
    if args.command=='prepare':
        out=args.output_dir or (args.repo.expanduser().resolve().parent/'AzLLM_Abstention_Human_Audit')
        prepare(args.repo.expanduser().resolve(),out.expanduser().resolve())
    else: analyze(args.output_dir.expanduser().resolve())
if __name__=='__main__': main()
